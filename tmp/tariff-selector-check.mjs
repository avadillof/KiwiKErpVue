import fs from "node:fs";
import assert from "node:assert/strict";
import {DatabaseSync} from "node:sqlite";
const base="C:/Proyectos/KiwiKERP/K_ERP_FREELANDSITE/src/main/java/com/freelandsite/api/";
const source=fs.readFileSync(base+"repositories/RepositoryProducts.java","utf8");
const block=source.slice(source.indexOf('@Query(value = "SELECT p.*'),source.indexOf("Page<ProductProduct> findEligibleSalesQuoteProducts"));
const split=block.split("countQuery =");
const extract=s=>[...s.matchAll(/"([^"]*)"/g)].map(m=>m[1]).join("");
const queries=[extract(split[0]),extract(split[1])];
const db=new DatabaseSync(":memory:");
db.function("CONCAT", {varargs:true}, (...args)=>args.join(""));
db.exec("CREATE TABLE categories(CATEGORIES_PK_ID INTEGER,CATEGORIES_BOL_DELETED INTEGER);CREATE TABLE product_product(id INTEGER,CATEGORIES_PK_ID INTEGER,PRODUCT_PRODUCT_BOL_DELETED INTEGER,PRODUCT_PRODUCT_BOL_ACTIVE INTEGER,PRODUCT_PRODUCT_DS_COD TEXT,PRODUCT_PRODUCT_DS_DESCRIPTIONSP TEXT,PRODUCT_PRODUCT_DS_BARCODE TEXT);INSERT INTO categories VALUES(1,NULL),(2,0),(3,1);");
const insert=db.prepare("INSERT INTO product_product VALUES(?,?,?,?,?,?,?)");
for(const row of [[1,1,0,1],[2,2,0,1],[3,3,0,1],[4,null,0,1],[5,1,1,1],[6,1,0,0]])insert.run(...row,"P"+row[0],"Product","");
assert.deepEqual(db.prepare(queries[0]).all({query:""}).map(r=>r.id),[1,2,4]);
assert.equal(Object.values(db.prepare(queries[1]).get({query:""}))[0],3);
assert.equal(db.prepare(queries[0]).all({query:"P1"}).length,1);
const pricing=fs.readFileSync(base+"services/SalesPricingService.java","utf8");
const jpql=pricing.match(/"select c from Categories c [^"]+"/)[0].slice(1,-1);
db.exec("CREATE TABLE family_test(categoriesTypesPkId INTEGER,categoriesBolDeleted INTEGER,categoriesBolActive INTEGER,categoriesDsDescriptionsp TEXT);INSERT INTO family_test VALUES(4,NULL,1,'New'),(4,0,1,'Existing'),(4,1,1,'Deleted'),(4,0,0,'Inactive'),(6,0,1,'Other type');");
const familySql=jpql.replace("select c from Categories c","select c.categoriesDsDescriptionsp from family_test c");
assert.deepEqual(db.prepare(familySql).all().map(r=>r.categoriesDsDescriptionsp),["Existing","New"]);
console.log("PASS: product and count SQL; family query predicates; null flags, inactive/deleted exclusions, family without products and search.");