import fs from 'node:fs';
import assert from 'node:assert/strict';
import ts from 'typescript';
import {parse} from '@vue/compiler-sfc';
const source=fs.readFileSync('src/views/Ventas/Frm_AjustesVentas/PaymentTermsSettings.vue','utf8');
const ast=ts.createSourceFile('sample.ts',parse(source).descriptor.scriptSetup.content,ts.ScriptTarget.Latest,true);
const fn=ast.statements.find(s=>ts.isFunctionDeclaration(s)&&s.name?.text==='sampleDay');
const code=ts.transpileModule(fn.getText(ast),{compilerOptions:{target:ts.ScriptTarget.ES2022}}).outputText;
const day=new Function(code+';return sampleDay;')();
assert.equal(day(new Date(2026,7,31,0,5)),'2026-08-31');
assert.equal(day(new Date(2026,9,25,23,55)),'2026-10-25');
assert.throws(()=>day(null));
assert.throws(()=>day(new Date('invalid')));
assert.ok(source.includes('dateFormat="dd/mm/yy"'));
assert.ok(!source.includes('type="date"'));
const parent=fs.readFileSync('src/views/Ventas/Frm_AjustesVentas/Frm_AjustesVentas.vue','utf8');
const section=parent.split('<TabPanel value="general">')[1].split('</TabPanel>')[0];
assert.ok(section.trim().endsWith('<PaymentTermsSettings/>'));
console.log('PASS: 7 isolated date, PrimeVue field and panel-position checks.');
